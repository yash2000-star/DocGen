const cloneRepo = require("./gitServices");
const scanCodeFiles= require("./codeScanner");
const generateDocs = require("./aiWriter");
const fs = require("fs");
const path = require("path");
const { exec } = require("child_process");

async function testPipeline() {
    const repoUrl = "https://github.com/yash2000-star/to-do-list";
    const projectName = "to-do-list";
    const tenantName = "yash";

    try {
        console.log("Starting the Delivery Driver...");
        const downloadedFolderPath = await cloneRepo(repoUrl, projectName);

        console.log("\n Sending in the Inspector...");
        const foundFiles = scanCodeFiles(downloadedFolderPath);

        console.log(`\n Success! The Inspector found ${foundFiles.length} code files!`);

       if (foundFiles.length > 0) {
            const firstFile = foundFiles[0];
            
            const markdownOutput = await generateDocs(firstFile); 
            
            console.log("\n==========================================");
            console.log("📝 FINAL DOCUMENTATION GENERATED BY AI:");
            console.log("==========================================\n");
            console.log(markdownOutput);
            console.log("\n==========================================");

            console.log("\n Saving documentation to the docs folder...");

            // Create: docs/yash/tp-do-list
            const targetDir = path.join(__dirname, "../docs", tenantName, projectName);
            if (!fs.existsSync(targetDir)) {
                fs.mkdirSync(targetDir, { recursive: true });
            }

            const originalFileName = path.basename(firstFile.path, path.extname(firstFile.path));
            const mdFilePath = path.join(targetDir,`${originalFileName}.md`);

            fs.writeFileSync(mdFilePath, markdownOutput);
            console.log(`Saved file exactly here: ${mdFilePath}`);

            console.log("\n Waking up the Factory Worker (build.js)...");
            const buildScriptPath = path.join(__dirname, "../build/build.js");

            exec(`node "${buildScriptPath}"`, (error, stdout, stderr) => {
                if (error) {
                    console.error("Factory Build failed:", stderr);
                    return;
                }
                console.log("\n Factory Worker Output:\n", stdout);
                console.log("PIPELINE COMPLETE! The docs are compled, vectorized, and live in the Cloud!")
            })
        }
        } catch (error) {
        console.error("Something went wrong:", error);
    }
}

testPipeline();
